#!/usr/bin/env node
// Writes src/git-version.generated.ts with the current git commit hash and time.
// Checks:
// 1. Git (if available, e.g. local build)
// 2. CI/CD environment variables (e.g. Render, Vercel, Cloudflare Pages, GitHub Actions in Docker)
// 3. Fallback to preserving existing committed file if neither is available.
import { execSync } from 'child_process';
import { writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

let hash, time;
try {
  hash = execSync('git rev-parse --short HEAD', { cwd: root, encoding: 'utf-8' }).trim();
  time = execSync('git log -1 --format=%cI', { cwd: root, encoding: 'utf-8' }).trim();
} catch {
  // git not available (e.g. Docker build where .git is excluded)
  const envCommit =
    process.env.RENDER_GIT_COMMIT ||
    process.env.VERCEL_GIT_COMMIT_SHA ||
    process.env.CF_PAGES_COMMIT_SHA ||
    process.env.COMMIT_REF ||
    process.env.GITHUB_SHA ||
    process.env.GIT_COMMIT;

  if (envCommit) {
    hash = envCommit.trim().slice(0, 7);
    time = new Date().toISOString();
    console.log(`[git-version] git unavailable, resolved from CI environment: hash=${hash}`);
  } else {
    // keep the committed file as-is.
    console.log('[git-version] git unavailable and no CI commit env var, keeping existing generated file.');
    process.exit(0);
  }
}

const content = `// AUTO-GENERATED by scripts/write-git-version.mjs — do not edit manually.
// Commit this file so Docker builds (which exclude .git) always have version info.
export const GIT_COMMIT_HASH = ${JSON.stringify(hash)};
export const GIT_COMMIT_TIME = ${JSON.stringify(time)};
`;

writeFileSync(join(root, 'src/git-version.generated.ts'), content, 'utf-8');
console.log(`[git-version] hash=${hash} time=${time}`);
