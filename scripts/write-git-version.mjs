#!/usr/bin/env node
// Writes src/git-version.generated.ts with the current git commit hash and time.
// IMPORTANT: If git is unavailable (e.g. inside Docker where .git is excluded),
// this script exits WITHOUT overwriting the file, preserving the committed value.
import { execSync } from 'child_process';
import { writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

let hash, time;
try {
  hash = execSync('git rev-parse --short HEAD', { cwd: root, encoding: 'utf-8' }).trim();
  time = execSync('git log -1 --format=%cI', { cwd: root, encoding: 'utf-8' }).trim();
} catch {
  // git not available (e.g. Docker build without .git) — keep the committed file as-is.
  console.log('[git-version] git unavailable, keeping existing generated file.');
  process.exit(0);
}

const content = `// AUTO-GENERATED by scripts/write-git-version.mjs — do not edit manually.
// Commit this file so Docker builds (which exclude .git) always have version info.
export const GIT_COMMIT_HASH = ${JSON.stringify(hash)};
export const GIT_COMMIT_TIME = ${JSON.stringify(time)};
`;

writeFileSync(join(root, 'src/git-version.generated.ts'), content, 'utf-8');
console.log(`[git-version] hash=${hash} time=${time}`);
