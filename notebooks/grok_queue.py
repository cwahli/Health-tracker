def _fix_key(k):
    """Rebuild an OpenSSH private key whose line breaks were lost when pasted into Secrets."""
    import re, textwrap
    k = k.strip().replace("\\n", "\n").replace("\r", "")
    m = re.search(r"-----BEGIN ([A-Z ]+)-----(.*?)-----END \1-----", k, re.S)
    if not m:
        body = re.sub(r"[^A-Za-z0-9+/=]", "", re.sub(r"-----[A-Z ]+-----", "", k))
        if body.startswith("b3BlbnNzaC1rZXktdjE"):
            return "-----BEGIN OPENSSH PRIVATE KEY-----\n" + "\n".join(textwrap.wrap(body, 70)) + "\n-----END OPENSSH PRIVATE KEY-----\n"
        return k + "\n"
    body = re.sub(r"\s+", "", m.group(2))
    return f"-----BEGIN {m.group(1)}-----\n" + "\n".join(textwrap.wrap(body, 70)) + f"\n-----END {m.group(1)}-----\n"

def _save_tg(home, token, chat_id):
    """Pass the Telegram bot token to the chat relay (Secrets are only readable inside the notebook)."""
    if not token or "YOUR_TELEGRAM" in token:
        return
    p = f"{home}/.grokq.tg"
    fd = os.open(p, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        json.dump({"token": token.strip(), "chat_id": int(chat_id or os.environ.get("COLLAB_CHAT_ID", "6218257274"))}, f)
    os.chmod(p, 0o600)

