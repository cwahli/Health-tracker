def _kill_old(pidf):
    """Stop the previous loop by its PID only (never pattern-kill: that can hit the launching shell).
    Running jobs/chat/ollama are separate processes; the new loop adopts them via ~/.grokq.run/*.pid."""
    import time
    try:
        pid = int(open(pidf).read().strip())
    except Exception:
        return
    try:
        cmd = open(f"/proc/{pid}/cmdline", "rb").read().replace(b"\0", b" ").decode(errors="replace")
    except Exception:
        return  # not running
    if "grokq.sh" not in cmd or pid == os.getpid():
        return  # PID reused by something else
    try:
        os.kill(pid, 15)
        for _ in range(50):
            time.sleep(0.1)
            if not os.path.exists(f"/proc/{pid}"):
                break
        print(f"• Grok queue: stopped old runner pid {pid}.")
    except Exception:
        pass

